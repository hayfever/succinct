#!/usr/bin/env python3
"""Rebuild every adapter file derived from the canonical skill.

The canonical skill is skills/succinct/SKILL.md plus its references/ folder.
package.json owns the package version. This script writes:

- .cursor/skills/succinct/, a copy of the whole skill folder. SKILL.md carries
  a note that marks it generated; references/ is copied byte for byte.
- metadata.version in skills/succinct/SKILL.md.
- the version field in every plugin and extension manifest.

Every other harness file is hand-written. Their prose is not a mechanical copy
of the skill, so freezing it here would create a second source of truth.

Usage:
    python3 scripts/build_adapters.py
    python3 scripts/build_adapters.py --check

--check writes nothing. It prints one unified diff per stale file and exits 1.
A file removed from the canonical folder is reported as a deletion from the
mirror.

The JSON manifests cannot carry the generated note. JSON has no comments, and
the harnesses parse these files with a strict parser.
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

CANONICAL_DIR = "skills/succinct"
MIRROR_DIR = ".cursor/skills/succinct"
CANONICAL = f"{CANONICAL_DIR}/SKILL.md"
PACKAGE = "package.json"

# Manifests that carry the package version. The marketplace manifests have no
# version field: they point at the plugin, which owns it.
VERSIONED_MANIFESTS = (
    ".claude-plugin/plugin.json",
    ".codex-plugin/plugin.json",
    "kimi.plugin.json",
    "qwen-extension.json",
    "gemini-extension.json",
)

GENERATED_NOTE = (
    "# Generated by scripts/build_adapters.py from skills/succinct/SKILL.md; "
    "do not edit."
)

FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)
SEMVER = re.compile(r"\A[0-9]+\.[0-9]+\.[0-9]+\Z")
YAML_VERSION = re.compile(
    r"""(?m)^(\s+version:\s*["']?)([0-9]+\.[0-9]+\.[0-9]+)(["']?)\s*$"""
)
JSON_VERSION = re.compile(r'("version"\s*:\s*")([^"]*)(")')


@dataclass(frozen=True)
class Change:
    """One stale derived file. ``new`` is None when the file must be removed."""

    relative: str
    old: str
    new: str | None

    def diff(self) -> str:
        return "".join(
            difflib.unified_diff(
                self.old.splitlines(keepends=True),
                (self.new or "").splitlines(keepends=True),
                fromfile=f"{self.relative} (on disk)",
                tofile=f"{self.relative} (generated)",
            )
        )


class BuildError(Exception):
    """A source file cannot be rebuilt without guessing or losing content."""


def read_text(path: Path, relative: str) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as error:
        raise BuildError(f"Cannot read {relative}: {error}") from error


def read_json(path: Path, relative: str) -> dict:
    text = read_text(path, relative)
    try:
        data = json.loads(text)
    except json.JSONDecodeError as error:
        raise BuildError(f"Fix the JSON in {relative}: {error}") from error
    if not isinstance(data, dict):
        raise BuildError(f"{relative} must contain a JSON object")
    return data


def package_version(root: Path) -> str:
    data = read_json(root / PACKAGE, PACKAGE)
    version = data.get("version")
    if not isinstance(version, str) or SEMVER.fullmatch(version) is None:
        raise BuildError(f"{PACKAGE} must declare a three-part version")
    return version


def frontmatter(text: str, relative: str) -> re.Match[str]:
    match = FRONTMATTER.match(text)
    if match is None:
        raise BuildError(f"{relative} must begin with a YAML frontmatter block")
    fields = match.group(1)
    for field in ("name", "description"):
        if re.search(rf"(?m)^{field}:\s*\S", fields) is None:
            raise BuildError(f"{relative} must declare {field} in its frontmatter")
    return match


def set_skill_version(text: str, version: str, relative: str) -> str:
    match = frontmatter(text, relative)
    fields, count = YAML_VERSION.subn(
        lambda found: f"{found.group(1)}{version}{found.group(3)}",
        match.group(1),
        count=1,
    )
    if count != 1:
        raise BuildError(
            f"{relative} must declare metadata.version as a three-part version"
        )
    return f"---\n{fields}\n---\n" + text[match.end():]


def set_manifest_version(text: str, version: str, relative: str) -> str:
    match = JSON_VERSION.search(text)
    if match is None:
        raise BuildError(f"{relative} must declare a version")
    updated = text[: match.start(2)] + version + text[match.end(2) :]
    try:
        data = json.loads(updated)
    except json.JSONDecodeError as error:
        raise BuildError(f"Fix the JSON in {relative}: {error}") from error
    if data.get("version") != version:
        raise BuildError(f"{relative} must declare the version at the top level")
    return updated


def mirror_text(canonical: str) -> str:
    """Copy the canonical skill and mark the copy inside the YAML frontmatter.

    A note before the opening fence or after the body would change how a
    harness finds the skill block or what the skill injects. A YAML comment
    survives both parsers and disappears when a harness strips the frontmatter.
    """
    if not canonical.startswith("---\n"):
        raise BuildError(f"{CANONICAL} must begin with a YAML frontmatter block")
    return f"---\n{GENERATED_NOTE}\n" + canonical[len("---\n") :]


def read_optional(path: Path, relative: str) -> str | None:
    """Read a generated copy that may not exist yet."""
    if not path.exists():
        return None
    return read_text(path, relative)


def canonical_files(root: Path) -> dict[str, str]:
    """Return every file in the canonical skill folder, keyed by relative path."""
    directory = root / CANONICAL_DIR
    if not directory.is_dir():
        raise BuildError(f"Cannot read {CANONICAL_DIR}: not a directory")
    files: dict[str, str] = {}
    for path in sorted(directory.rglob("*")):
        if path.is_file():
            relative = path.relative_to(directory).as_posix()
            files[relative] = read_text(path, f"{CANONICAL_DIR}/{relative}")
    if "SKILL.md" not in files:
        raise BuildError(f"{CANONICAL} is missing from {CANONICAL_DIR}")
    return files


def plan(root: Path) -> list[Change]:
    """Return every stale derived file. The disk is not modified."""
    version = package_version(root)
    canonical = read_text(root / CANONICAL, CANONICAL)
    next_canonical = set_skill_version(canonical, version, CANONICAL)
    sources = canonical_files(root)

    targets: list[tuple[str, str, str | None]] = [
        (CANONICAL, canonical, next_canonical)
    ]
    for relative, text in sources.items():
        target = f"{MIRROR_DIR}/{relative}"
        current = read_optional(root / target, target)
        new = mirror_text(next_canonical) if relative == "SKILL.md" else text
        targets.append((target, "" if current is None else current, new))

    mirror_dir = root / MIRROR_DIR
    if mirror_dir.is_dir():
        for path in sorted(mirror_dir.rglob("*")):
            if not path.is_file():
                continue
            relative = path.relative_to(mirror_dir).as_posix()
            if relative not in sources:
                target = f"{MIRROR_DIR}/{relative}"
                targets.append((target, read_text(path, target), None))

    for relative in VERSIONED_MANIFESTS:
        current = read_text(root / relative, relative)
        targets.append(
            (relative, current, set_manifest_version(current, version, relative))
        )

    return [
        Change(relative, old, new)
        for relative, old, new in targets
        if old != new
    ]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="print a diff for each stale file and exit 1 instead of writing",
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=ROOT,
        help="repository root (default: the checkout that holds this script)",
    )
    args = parser.parse_args(argv)
    root = args.root.resolve()

    try:
        changes = plan(root)
    except BuildError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    if args.check:
        for change in changes:
            print(change.diff(), end="")
        if changes:
            print(
                f"{len(changes)} generated file(s) are out of date. "
                "Run python3 scripts/build_adapters.py.",
                file=sys.stderr,
            )
            return 1
        print("generated adapters are up to date")
        return 0

    for change in changes:
        path = root / change.relative
        if change.new is None:
            path.unlink()
            print(f"removed {change.relative}")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(change.new, encoding="utf-8", newline="\n")
        print(f"wrote {change.relative}")
    if not changes:
        print("generated adapters are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
